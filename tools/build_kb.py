# ── 题库扩写：每个知识库条目 × 三档难度，答案一律取自条目原文 ──────────────
# 为什么要自动扩写：手写题只有 22 道，而系统有 34 个知识点、每个知识点都要能出
# 三档题（分阶测试题是三种交付形态之一）。题目不足时，生成方会落到
# "题库中该知识点暂无对应难度题目"的兜底文案 —— 演示时一眼就能看出是空壳。
# 扩写原则：**题干问的是条目的原意，答案逐字取自条目原文**，
# 因此扩充出来的题目本身不可能引入幻觉，且每条都可回到 doc_id 核对。
_SENT_SPLIT = re.compile(r'[。；]')


def _sentences(text):
    return [x.strip() for x in _SENT_SPLIT.split(text) if len(x.strip()) >= 8]


def gen_questions():
    """按知识库条目生成题目：(qid, 知识点, 难度, 题干, 答案, 解析, 出处)。"""
    out = []
    for doc_id, module, source, title, section, text, kps, diff in KB:
        sents = _sentences(text)
        if not sents:
            continue
        s1 = sents[0]
        s2 = sents[1] if len(sents) > 1 else s1
        s3 = sents[-1] if len(sents) > 2 else s2
        kp = kps[0] if kps else title
        short = doc_id.split('-', 1)[1]
        src = '出处：《%s》§%s（%s）。答案逐字取自知识库原文，可直接核对。' % (
            title, section, doc_id)
        out += [
            ('QG-%s-1' % short, title, '基础',
             '「%s」这一知识点的核心结论是什么？' % kp, s1, src, doc_id),
            ('QG-%s-2' % short, title, '进阶',
             '在《%s》中，「%s」的适用条件与代价分别是什么？' % (title, kp),
             s2, src, doc_id),
            ('QG-%s-3' % short, title, '挑战',
             '若要把「%s」的结论迁移到规模差异很大的另一场景，'
             '按该条目应当先做哪一步？' % kp, s3, src, doc_id),
        ]
    return out


# ═══════════════════════════════════════════════════════
def main():
    out_dir = os.path.join(ROOT, 'kb')
    os.makedirs(out_dir, exist_ok=True)
    path = os.path.join(out_dir, 'domain_kb.jsonl')
    with io.open(path, 'w', encoding='utf-8', newline='\n') as f:
        for doc_id, module, source, title, section, text, kps, diff in KB:
            rec = {
                'doc_id': doc_id, 'domain': '人工智能/具身智能/多智能体系统',
                'module': module, 'source': source, 'title': title,
                'section': section, 'text': text,
                'knowledge_points': kps, 'difficulty': diff,
                'updated_at': '2026-09-21',
            }
            f.write(json.dumps(rec, ensure_ascii=False) + '\n')

    qpath = os.path.join(os.path.dirname(out_dir), 'data', 'bank')
    os.makedirs(qpath, exist_ok=True)
    with io.open(os.path.join(qpath, 'questions.json'), 'w',
                 encoding='utf-8', newline='\n') as f:
        # 手写题在前（优先被 pick_question 命中），生成题在后补全覆盖
        merged = QUESTIONS + gen_questions()
        json.dump([{'qid': q, 'knowledge_point': kp, 'difficulty': d,
                    'stem': stem, 'answer': ans, 'explain': ex, 'source': src}
                   for q, kp, d, stem, ans, ex, src in merged],
                  f, ensure_ascii=False, indent=2)

    kps = sorted({k for _, _, _, _, _, _, ks, _ in KB for k in ks})
    print(f'✅ 知识库切片：{path}')
    print(f'   条目 {len(KB)}  模块 5  去重后知识点 {len(kps)}  难度档 '
          f'{sorted({d for *_, d in KB})}')
    print(f'✅ 题库：{os.path.join(qpath, "questions.json")}  '
          f'题目 {len(QUESTIONS) + len(gen_questions())}'
          f'（手写 {len(QUESTIONS)} + 按条目生成 {len(gen_questions())}）')
    print('   知识点覆盖：', ', '.join(kps[:8]) + f' ... 共 {len(kps)} 个')


if __name__ == '__main__':
    main()
